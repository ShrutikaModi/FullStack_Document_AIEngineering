"""Record the demo examples: run three real questions through the real agent and write the
answers, progress lines and source cards into app/demo/recorded.py.

Run from backend/ (it makes real model calls, about 5 cents; needs the database and Azure key):

    uv run python -m evals.record_demo

An answer is recorded only if it passes app/demo/checks.py (sources numbered in order of use,
each cited source states a figure the answer gives, percentages quoted or correctly
calculated); otherwise it is recorded again, up to ATTEMPTS times. Then READ the printed
answers against the filings and run `uv run pytest tests/demo` before committing. Run it again
after re-ingesting the filings, so the stored chunk ids stay valid.
"""

import asyncio
import json
from pathlib import Path
from pprint import pformat

from app.assistant.agent import build_agent
from app.assistant.deps import DocumentAgentDeps
from app.assistant.model import create_chat_model
from app.assistant.outputs import GroundedAnswer
from app.chat.orchestrator import run_agent
from app.chat.sources import build_sources
from app.database.engine import create_db_engine
from app.demo.checks import check_example, renumber
from app.openai_client import create_async_openai_client
from app.retrieval.retriever import DocumentRetriever, openai_embedder

# How many times one question may be recorded before giving up (each try is a few cents).
ATTEMPTS = 5

OUTPUT = Path(__file__).resolve().parent.parent / "app" / "demo" / "recorded.py"

# (id, company, kind shown on the card, question). One company and one kind of question each.
QUESTIONS = [
    (
        "apple-net-sales",
        "Apple",
        "Single figure",
        "What was Apple's total net sales in fiscal 2024?",
    ),
    (
        "amazon-aws-margin",
        "Amazon",
        "Comparison",
        "For Amazon, compare AWS operating income and margin against North America and International.",
    ),
    (
        "nvidia-data-center",
        "NVIDIA",
        "Narrative disclosure",
        "How did NVIDIA describe demand drivers, customer concentration, and supply constraints for its Data Center business?",
    ),
]


async def record_one(agent, retriever, question: str) -> dict:
    deps = DocumentAgentDeps("demo-recorder", "demo-recorder", retriever)
    steps: list[str] = []
    answer: GroundedAnswer | None = None
    async for item in run_agent(agent, question, deps, []):
        if isinstance(item, GroundedAnswer):
            answer = item
        else:  # a progress event: "data: {...}\n\n"
            steps.append(json.loads(item.removeprefix("data: "))["data"]["text"])
    if answer is None or not answer.enough_evidence or not answer.citations:
        return {"problems": ["no cited answer"]}
    text, sources = renumber(
        answer.answer.strip(), build_sources(answer, deps.evidence)
    )
    return {
        "steps": steps,
        "answer": text,
        "sources": sources,
        "problems": check_example(text, sources),
    }


async def record_checked(agent, retriever, question: str) -> dict:
    """Record the question, trying again until the answer passes app/demo/checks.py."""
    for attempt in range(1, ATTEMPTS + 1):
        one = await record_one(agent, retriever, question)
        problems = one.pop("problems")
        if not problems:
            return one
        print(f"  attempt {attempt} rejected:")
        for problem in problems:
            print(f"    - {problem}")
    raise SystemExit(
        f"No answer passed the checks after {ATTEMPTS} attempts: {question}"
    )


async def main() -> None:
    engine = create_db_engine()
    retriever = DocumentRetriever(engine, openai_embedder(create_async_openai_client()))
    agent = build_agent(create_chat_model())

    recorded = []
    for example_id, company, kind, question in QUESTIONS:
        print(f"recording {example_id} ...")
        one = await record_checked(agent, retriever, question)
        recorded.append(
            {"id": example_id, "company": company, "kind": kind, "question": question}
            | one
        )
        print(f"\n{one['answer']}\n")
    await engine.dispose()

    OUTPUT.write_text(
        '"""Recorded answers for the demo. Generated by evals/record_demo.py: do not edit by hand."""\n\n'
        f"RECORDED = {pformat(recorded, width=100, sort_dicts=False)}\n"
    )
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    asyncio.run(main())
